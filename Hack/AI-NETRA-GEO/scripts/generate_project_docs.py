def discover_files():
    output = []
    for path in ROOT.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT)
        if any(part in SKIP_DIRS for part in rel.parts) or path.suffix.lower() in SKIP_SUFFIXES:
            continue
        name = rel.as_posix()
        purpose = PURPOSES.get(name, "Review purpose; not yet documented individually.")
        output.append({"path": name, "size_bytes": path.stat().st_size, "purpose": purpose})
    return sorted(output, key=lambda x: x["path"].lower())


def count_records(filename, kind):
    file = ROOT / "data" / filename
    if not file.exists():
        return "file not found"
    try:
        if kind == "geojson":
            with file.open(encoding="utf-8-sig") as stream:
                return len(json.load(stream).get("features", []))
        if kind == "csv":
            with file.open(encoding="utf-8-sig", newline="") as stream:
                return sum(1 for _ in csv.DictReader(stream))
    except (OSError, ValueError, TypeError, csv.Error) as exc:
        return f"could not count ({type(exc).__name__})"
    return "unknown"


def api_routes(file_name):
    file = ROOT / file_name
    if not file.exists():
        return []
    try:
        tree = ast.parse(file.read_text(encoding="utf-8-sig"))
    except (OSError, SyntaxError, UnicodeError):
        return []
    routes = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for decorator in node.decorator_list:
            if not isinstance(decorator, ast.Call) or not isinstance(decorator.func, ast.Attribute):
                continue
            if decorator.func.attr not in {"get", "post", "put", "delete", "patch"}:
                continue
            if not decorator.args or not isinstance(decorator.args[0], ast.Constant):
                continue
            routes.append((decorator.func.attr.upper(), str(decorator.args[0].value), node.name))
    return routes


def python_dependencies():
    versions = []
    for filename in ("requirements.txt", "pyproject.toml", "Pipfile"):
        file = ROOT / filename
        if file.exists():
            versions.append(f"- `{filename}` is present; treat it as the dependency declaration.")
    return "\n".join(versions) if versions else "- No Python dependency manifest found at project root; export a reviewed `requirements.txt` before handoff."


def frontend_dependencies():
    file = ROOT / "frontend" / "package.json"
    if not file.exists():
        return "Frontend package.json not found."
    try:
        data = json.loads(file.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return "Frontend package.json could not be parsed."
    rows = ["| Package | Declared version |", "|---|---|"]
    for key, version in sorted({**data.get("dependencies", {}), **data.get("devDependencies", {})}.items()):
        rows.append(f"| `{key}` | `{version}` |")
    return "\n".join(rows)


def write_generated(name, body):
    path = DOCS / name
    if path.exists():
        existing = path.read_text(encoding="utf-8-sig")
        if existing.strip() and not existing.startswith(MARKER):
            print(f"PRESERVED (manual): {name}")
            return
    path.write_text(f"{MARKER}\n\n{body.strip()}\n", encoding="utf-8")
    print(f"GENERATED: {name}")


